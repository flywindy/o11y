func TestSemconvKeys(t *testing.T) {
	keys, err := semconvKeys()
	if err != nil {
		t.Fatal(err)
	}
	// A partial parse, not only an empty one, must fail here: the pinned
	// package declares several hundred keys across its files.
	if len(keys) < 500 {
		t.Errorf("semconvKeys found %d keys, want several hundred", len(keys))
	}
	for _, key := range []string{"service.name", "server.address", "db.system.name", "error.type", "messaging.destination.name"} {
		if !keys[key] {
			t.Errorf("semconvKeys is missing %q", key)
		}
	}
}

func TestScan(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		t.Helper()
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("pkg/flagged.go", "package pkg\n\nvar a = \"server.address\"\nvar b = `service.name`\nvar c = \"app.order.id\"\n")
	write("pkg/flagged_test.go", "package pkg\n\nvar d = \"server.address\"\n")
	write("pkg/gen.go", "// Code generated by x; DO NOT EDIT.\n\npackage pkg\n\nvar e = \"server.address\"\n")
	write("pkg/imports.go", "package pkg\n\nimport _ \"server.address\"\n")
	write("examples/app/main.go", "package main\n\nvar f = \"server.address\"\n")
	write("pkg/examples/inner.go", "package examples\n\nvar g = \"server.address\"\n")
	write("pkg/testdata/x.go", "package x\n\nvar h = \"server.address\"\n")
	write(".hidden/x.go", "package x\n\nvar i = \"server.address\"\n")

	findings, err := scan(root, map[string]bool{"server.address": true, "service.name": true})
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, f := range findings {
		rel, _, _ := strings.Cut(strings.TrimPrefix(f, root+string(filepath.Separator)), ": ")
		got = append(got, filepath.ToSlash(rel))
	}
	want := []string{"pkg/examples/inner.go:3:9", "pkg/flagged.go:3:9", "pkg/flagged.go:4:9"}
	slices.Sort(got)
	if !slices.Equal(got, want) {
		t.Errorf("scan findings = %v, want %v", got, want)
	}
}
